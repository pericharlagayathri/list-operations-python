# Unit III - Experiment 25: Create a list and perform list operations

numbers = [10, 20, 30, 40]

print("Original list:", numbers)

numbers.append(50)
print("After append:", numbers)

numbers.insert(1, 15)
print("After insert:", numbers)

numbers.remove(30)
print("After remove:", numbers)

numbers.sort()
print("After sort:", numbers)

numbers.reverse()
print("After reverse:", numbers)
